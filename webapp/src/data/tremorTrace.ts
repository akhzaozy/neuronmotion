/**
 * Rekaman tremor yang ditampilkan di halaman depan.
 *
 * Isinya saat ini adalah CONTOH POLA yang dibangkitkan, bukan pengukuran
 * siapa pun. Karena itu `kind` bernilai 'illustration', dan keterangan di
 * halaman depan menyebutnya sebagai contoh, bukan sebagai rekaman. Halaman
 * depan produk ini menampilkan angka akurasi lengkap dengan asal-usulnya,
 * jadi pola buatan tidak boleh pernah mengaku sebagai hasil pengukuran.
 *
 * Dibangkitkan oleh .gen-trace.mjs dengan acak berbenih, jadi dapat dibangun
 * ulang persis sama. Bentuknya meniru ciri tremor istirahat: frekuensi sekitar
 * 5 Hz, selubung yang menguat dan melemah, fase yang mengembara pelan, satu
 * harmonik lemah, dan sedikit derau.
 *
 * Bila nanti ada rekaman sungguhan yang layak, ganti isinya dan setel `kind`
 * ke 'recording'. Keterangan di halaman depan akan ikut berubah sendiri.
 *
 * Cara mengambil rekaman sungguhan:
 *
 *   1. Jalankan aplikasi, buka /demo?export=1
 *   2. Lakukan tes tremor sampai keluar hasilnya
 *   3. Tekan "Salin rekaman (JSON)" di bawah tabel hasil
 *   4. Tempel isinya menggantikan `null` di bawah, lalu simpan
 *
 * Yang direkam hanyalah koordinat pergelangan tangan terhadap waktu. Tidak ada
 * video, tidak ada gambar, dan tidak ada identitas siapa pun di dalamnya.
 */

export interface TremorSample {
  /** Milidetik sejak sampel pertama. */
  t: number;
  /** Koordinat pergelangan ternormalisasi 0..1 dari MediaPipe. */
  x: number;
  y: number;
}

export interface TremorTrace {
  /**
   * Asal-usul data, dan ini bukan sekadar catatan.
   *
   * Keterangan di halaman depan dipilih berdasarkan nilai ini: 'recording'
   * menghasilkan kalimat yang menyebut rekaman sungguhan, 'illustration'
   * menghasilkan kalimat yang menyebut contoh pola. Dengan begitu label tidak
   * bisa tertinggal ketika datanya berganti, dan tidak ada jalan untuk secara
   * tidak sengaja menyebut pola buatan sebagai pengukuran seseorang.
   */
  kind: 'recording' | 'illustration';
  /** Tanggal perekaman, format YYYY-MM-DD. Hanya untuk kind 'recording'. */
  capturedAt?: string;
  durationSec: number;
  dominantFrequencyHz: number;
  amplitudeMillimeter: number;
  samples: TremorSample[];
}

